/** 依据成绩查单项得分(0~75)。value 需为有效正数，否则返回 0。 */
export function scoreFor(gender: Gender, event: EventKey, value: number): number {
  if (!Number.isFinite(value) || value <= 0) return 0;
  const table = TABLES[gender][event];
  const eps = 1e-9;
  if (event === "sprint") {
    for (let s = MAX_SCORE; s >= 1; s--) {
      if (value <= table[s] + eps) return s;
    }
    return 0;
  }
  for (let s = MAX_SCORE; s >= 1; s--) {
    if (value + eps >= table[s]) return s;
  }
  return 0;
}

/** 某分值对应的达标成绩；sprint 为“不超过该秒数”，田赛为“达到该米数”。 */
export function perfForScore(gender: Gender, event: EventKey, score: number): number {
  return TABLES[gender][event][score];
}

export interface NextTarget {
  score: number;   // 再往上 1 分
  need: number;    // 要拿到 score 分所需的达标成绩
  delta: number;   // 还差多少（秒/米）
}

/** 距离更高一档还差多少；已是满分 75 则返回 null。 */
export function nextTarget(gender: Gender, event: EventKey, value: number): NextTarget | null {
  const s = scoreFor(gender, event, value);
  if (s >= MAX_SCORE || s <= 0) return null;
  const table = TABLES[gender][event];
  const need = table[s + 1];
  const delta = event === "sprint" ? value - need : need - value;
  return { score: s + 1, need, delta: Math.max(0, delta) };
}
