// ============ 工具函数 ============
function pick<T>(phase: PhaseKey, m: Record<PhaseKey, T>): T {
  return m[phase];
}
function ex(name: string, dose: string, intensity: string, rest: string, cue: string): ExerciseDoc {
  return { name, dose, intensity, rest, cue };
}

