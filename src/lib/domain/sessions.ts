// ============ 组装一周课表 ============
export interface WeekOptions {
  phase: PhaseKey;
  daysPerWeek: number; // 4 | 5 | 6
  weakKey: string;
}

export function buildWeekSchedule(opts: WeekOptions): DayDoc[] {
    const weak = opts.weakKey;
  const d6 = d6Weakness(opts.phase, weak);
  const all: DayDoc[] = [
    d1Speed(opts.phase),
    d2LowerStrength(opts.phase),
    d3SpeedEndurance(opts.phase),
    d4Jump(opts.phase),
    d5UpperStrength(opts.phase),
    { ...d6, day: 6 },
  ];
  let idx: number[];
  if (opts.daysPerWeek === 6) idx = [0, 1, 2, 3, 4, 5];
  else if (opts.daysPerWeek === 5) idx = [0, 1, 2, 3, 4];
  else idx = [0, 1, 3, 4]; // 4 天：速度、下肢力量+铅球技术、跳跃专项、全身力量+铅球
  const days = idx.map((i) => all[i]).map((d, k) => ({ ...d, day: k + 1 }));
  return days;
}

